"""usage: python -B fixround.py R TMAX FIRSTID8 FIRSTUUID FIRSTLABEL
Second pass after mkround.py: memory budget, pages, lineage text, dependencies (first dependency = our previous-round entry)."""
import sys, os, re, ast, math
R = int(sys.argv[1]); TM = int(sys.argv[2]); F8 = sys.argv[3]; FU = sys.argv[4]; FL = sys.argv[5]
W = {5: "five", 6: "six"}[R]
D = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "blake3_r%d" % R, "b%d" % R))
info = ast.literal_eval(open(os.path.join(D, "info.txt")).read())
code = info["code"]
base = code + 800 * 32 + 16384
ML = base + 64 + 10 * TM
mem = base + 10 * TM
pages = -(-info["static"] // 65536)
assert pages * 65536 <= mem, (pages, mem)
cap = pages * 65536
def rd(p): return open(os.path.join(D, p), encoding="utf-8", newline="").read()
def wr(p, t): open(os.path.join(D, p), "w", encoding="utf-8", newline="").write(t)
def rep(t, a, b, cnt=None):
    n = t.count(a)
    if cnt is not None: assert n == cnt, (a[:60], n)
    return t.replace(a, b)
generic = [("29 pages = 1,900,544 B at 7 rounds", "%d pages = %s B at %d rounds" % (pages, "{:,}".format(cap), R)),
           ("29 pages = 1,900,544 bytes", "%d pages = %s bytes" % (pages, "{:,}".format(cap))), ("29 pages (1,900,544", "%d pages (%s" % (pages, "{:,}".format(cap))),
           ("29 pages unused", "%d pages unused" % pages), ("1,900,544", "{:,}".format(cap)), ("at 7 rounds)", "at %d rounds)" % R), ("at 7 rounds (", "at %d rounds (" % R),
           ("at 7 rounds,", "at %d rounds," % R),
           ("blake3 round-7 profile", "blake3 round-%d profile" % R), ("BLAKE3, 7 rounds (full BLAKE3)", "BLAKE3, %d rounds" % R)]
for f in ("bsrho_x", "appA.py", "gen_c/gen.c", "build_all.py", "note_t.md", "proof_t.md", "gen_c/build_r7.py", "gen_c/vm_r7.py", "gen_c/make_cport.py", "pkg/blake3/experiments/bsrho.py"):
    if f == "bsrho_x": continue
    t = rd(f)
    for a, b in generic:
        t = t.replace(a, b)
    if f.endswith("bsrho.py"):
        t = re.sub(r"MEM_LIMIT = \d+", "MEM_LIMIT = %d" % ML, t)
    if f == "appA.py":
        t = re.sub(r"MEM_LIMIT = \d+", "MEM_LIMIT = %d" % ML, t)
        t = t.replace("proof 3.3)", "proof 3.8)")
    if f == "gen_c/build_r7.py": t = t.replace("max_pages=29", "max_pages=%d" % pages)
    if f == "gen_c/make_cport.py": t = t.replace("29 * 65536", "%d * 65536" % pages)
    if f == "gen_c/vm_r7.py": t = t.replace("MAX_PAGES = 29", "MAX_PAGES = %d" % pages)
    if f == "build_all.py":
        t = t.replace("(3000, 6000, 9000, 11500, 14000, 20000)", "(%d, %d, %d, %d, %d, %d)" % (3000, TM // 2, TM * 3 // 4, TM, TM * 5 // 4, TM * 2))
        t = t.replace("== 11500", "== %d" % TM)
    wr(f, t)
# gen.c in the experiments file (GEN_C) is regenerated by embed_gen.py after gen.c is final
print("MEM_LIMIT", ML, "mem", mem, "pages", pages, "cap", cap)
open(os.path.join(D, "plan.txt"), "w").write("ML %d mem %d pages %d tm %d\n" % (ML, mem, pages, TM))
