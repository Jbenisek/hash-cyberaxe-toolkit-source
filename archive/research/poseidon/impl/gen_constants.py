"""Generate constants_own.py from the PUBLIC upstream fp.rs (zcash/halo2 tag halo2_poseidon-0.2.0).
Reads upstream/fp.rs (curl'd raw file). Output: 192 round constants, MDS, MDS_INV as canonical ints."""
import re, sys
P = 0x40000000000000000000000000000000224698fc094cf91b992d30ed00000001
src = open('upstream/fp.rs').read()
vals = []
for m in re.finditer(r'from_raw\(\[(.*?)\]\)', src, re.S):
    limbs = [int(x.replace('_', ''), 16) for x in re.findall(r'0x[0-9a-fA-F_]+', m.group(1))]
    assert len(limbs) == 4
    v = sum(l << (64 * i) for i, l in enumerate(limbs))
    assert v < P
    vals.append(v)
assert len(vals) == 192 + 9 + 9, len(vals)
rc = [tuple(vals[3 * i:3 * i + 3]) for i in range(64)]
mds = [tuple(vals[192 + 3 * i:192 + 3 * i + 3]) for i in range(3)]
inv = [tuple(vals[201 + 3 * i:201 + 3 * i + 3]) for i in range(3)]
# MDS * MDS_INV == I
for i in range(3):
    for j in range(3):
        assert sum(mds[i][k] * inv[k][j] for k in range(3)) % P == (1 if i == j else 0)
with open('constants_own.py', 'w') as f:
    f.write('"""AUTO-GENERATED by gen_constants.py from upstream halo2_poseidon-0.2.0 fp.rs. Canonical integers (from_raw limbs are canonical LE)."""\n')
    f.write('P = 0x%x\n' % P)
    f.write('ROUND_CONSTANTS = (\n')
    for r in rc:
        f.write('    (' + ', '.join('0x%064x' % x for x in r) + '),\n')
    f.write(')\nMDS = (\n')
    for r in mds:
        f.write('    (' + ', '.join('0x%064x' % x for x in r) + '),\n')
    f.write(')\nMDS_INV = (\n')
    for r in inv:
        f.write('    (' + ', '.join('0x%064x' % x for x in r) + '),\n')
    f.write(')\n')
print('ok', len(rc), 'rows; MDS*MDS_INV = I')
