"""Generate pallas_consts.h (Montgomery-form constants) and cross-check vector files for the C library.
Run: python3 gen_c_consts.py   (reads the organizer JSON via poseidon_ref; writes next to this file)"""
import random, os, re
from poseidon_ref import *

HERE = os.path.dirname(os.path.abspath(__file__))
R = 1 << 256
S = 32
Q = (P - 1) >> S
assert (P - 1) == Q << S and Q & 1
assert pow(5, (P - 1) // 2, P) == P - 1, '5 must be a non-residue'
Z = pow(5, Q, P)                       # primitive 2^32-th root of unity
assert pow(Z, 1 << 31, P) == P - 1
INV = (-pow(P, -1, 1 << 64)) % (1 << 64)   # -p^{-1} mod 2^64
assert (INV * (P & (2**64 - 1)) + 1) % (1 << 64) == 0

def limbs(x): return [(x >> (64 * i)) & (2**64 - 1) for i in range(4)]
def lit(x): return '{{0x%016xULL,0x%016xULL,0x%016xULL,0x%016xULL}}' % tuple(reversed(limbs(x))) if False else \
    '{{' + ','.join('0x%016xULL' % l for l in limbs(x)) + '}}'
def mont(x): return (x * R) % P

out = []
out.append('/* GENERATED by gen_c_consts.py from the organizer JSON; limbs little-endian, values in Montgomery form */')
out.append('#ifndef PALLAS_CONSTS_H\n#define PALLAS_CONSTS_H')
out.append('#define PALLAS_INV 0x%016xULL /* -p^{-1} mod 2^64 */' % INV)
out.append('static const uint64_t PALLAS_P[4] = ' + '{' + ','.join('0x%016xULL' % l for l in limbs(P)) + '};')
out.append('static const uint64_t PALLAS_R2[4] = ' + '{' + ','.join('0x%016xULL' % l for l in limbs(R * R % P)) + '};')
out.append('static const uint64_t PALLAS_ONE_M[4] = ' + '{' + ','.join('0x%016xULL' % l for l in limbs(R % P)) + '};')
out.append('/* q = (p-1)/2^32, odd */')
out.append('static const uint64_t PALLAS_Q[4] = ' + '{' + ','.join('0x%016xULL' % l for l in limbs(Q)) + '};')
out.append('/* (q+1)/2 */')
out.append('static const uint64_t PALLAS_QP1H[4] = ' + '{' + ','.join('0x%016xULL' % l for l in limbs((Q + 1) // 2)) + '};')
out.append('/* (p-1)/2 */')
out.append('static const uint64_t PALLAS_PM1H[4] = ' + '{' + ','.join('0x%016xULL' % l for l in limbs((P - 1) // 2)) + '};')
out.append('/* p-2 */')
out.append('static const uint64_t PALLAS_PM2[4] = ' + '{' + ','.join('0x%016xULL' % l for l in limbs(P - 2)) + '};')
out.append('/* Z = 5^q, primitive 2^32-th root of unity (Montgomery form) */')
out.append('static const uint64_t PALLAS_Z_M[4] = ' + '{' + ','.join('0x%016xULL' % l for l in limbs(mont(Z))) + '};')
out.append('static const uint64_t POSEIDON_CAP_M[4] = ' + '{' + ','.join('0x%016xULL' % l for l in limbs(mont(CAPACITY))) + '}; /* 2^65 */')
out.append('static const fp POSEIDON_RC_M[64][3] = {')
for row in RC:
    out.append('  {' + ','.join('{{' + ','.join('0x%016xULL' % l for l in limbs(mont(x))) + '}}' for x in row) + '},')
out.append('};')
out.append('static const fp POSEIDON_MDS_M[3][3] = {')
for row in MDS:
    out.append('  {' + ','.join('{{' + ','.join('0x%016xULL' % l for l in limbs(mont(x))) + '}}' for x in row) + '},')
out.append('};')
out.append('#endif')
open(os.path.join(HERE, 'pallas_consts.h'), 'w').write('\n'.join(out) + '\n')

# ---- cross-check vectors (hex big-endian integers, 64 digits)
h = lambda x: '%064x' % x
random.seed(20261012)
lines = []
edge = [(0, 0), (0, 1), (1, 0), (P - 1, P - 1), (P - 1, 0), (0, P - 1), (P - 2, 12345), (1 << 253, (1 << 254) - 1)]
for r in (0, 1, 2):
    for a, b in edge:
        lines.append((r, a, b))
    for _ in range(1000):
        lines.append((r, random.randrange(P), random.randrange(P)))
for r in (3, 5, 10, 30, 55):
    for _ in range(20):
        lines.append((r, random.randrange(P), random.randrange(P)))
# public halo2_poseidon vectors at r = 56
src = open(os.path.join(HERE, 'upstream', 'test_vectors.rs')).read()
fp_src = src[src.index('pub mod fp'):src.index('pub mod fq')]
hs = fp_src[fp_src.index('pub fn hash'):]
nums = [int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})\b', hs)]
els = [int.from_bytes(bytes(nums[i:i + 32]), 'little') for i in range(0, len(nums), 32)]
for v in range(11):
    lines.append((56, els[3 * v], els[3 * v + 1]))
    assert hash_full(els[3 * v], els[3 * v + 1]) == els[3 * v + 2]
for _ in range(20):
    lines.append((56, random.randrange(P), random.randrange(P)))
with open(os.path.join(HERE, 'poseidon_vectors.txt'), 'w') as f:
    f.write('# r nk rho digest  (hex big-endian ints; produced by poseidon_ref.py; r=56 includes 11 public halo2_poseidon vectors)\n')
    for r, a, b in lines:
        f.write('%d %s %s %s\n' % (r, h(a), h(b), h(hash_reduced(a, b, r))))
print('poseidon vectors:', len(lines))

with open(os.path.join(HERE, 'field_vectors.txt'), 'w') as f:
    f.write('# a b a+b a-b a*b inv(a) legendre(a)(0/1/-1 as 0,1,2)  hex big-endian\n')
    n = 0
    for a, b in [(0, 0), (1, 1), (0, 5), (P - 1, P - 1), (P - 1, 1), (2, P - 1)] + [(random.randrange(P), random.randrange(P)) for _ in range(500)]:
        inv = pow(a, P - 2, P)
        lg = pow(a, (P - 1) // 2, P); lg = 0 if lg == 0 else (1 if lg == 1 else 2)
        f.write('%s %s %s %s %s %s %d\n' % (h(a), h(b), h((a + b) % P), h((a - b) % P), h(a * b % P), h(inv), lg))
        n += 1
print('field vectors:', n)
