"""Generates ntt_big.h: straight-line register-block kernels for the large transforms (ntt.c, 'big' plans).
usage: python3 gen_big.py KG KFMIN KFMAX
A big plan (a = KG + kf, KFMIN <= kf <= KFMAX) is run in two passes: a first pass of KG layers (blocks of 2^KG data words) and a last pass of
kf layers (blocks of 2^kf words, stride 1, the pass that is fused with the pointwise product).  Every kernel is straight-line text: no loop, no
branch, every register is a literal index x[n] of the register file RF.  Every statement that executes loads, stores, address or control
operations carries its charge on the same line (LD / ST / CTL); the field operations are charged by pallas.c (fp_bf and the others perform
exactly the three, two, three and two field operations written in their definitions)."""
import sys
KG, KFMIN, KFMAX = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
assert KFMAX < KG
o = ['/* generated by gen_big.py %d %d %d: straight-line register-block kernels and passes of the big plans; x[] is the register file RF */' % (KG, KFMIN, KFMAX),
     '#define BIG_KG %d' % KG, '#define BIG_KFMIN %d' % KFMIN, '#define BIG_KFMAX %d' % KFMAX,
     '#define BIG_RFW %d   /* words of the register file: 2^BIG_KG data words + 8 working words */' % ((1 << KG) + 8),
     '#define bgB(u, v)  fp_bf(&x[u], &x[v], w)',
     '#define bgBN(u, v) fp_bfn(&x[u], &x[v])',
     '#define bgJ(u, v)  fp_ib(&x[u], &x[v], w)',
     '#define bgJN(u, v) fp_ibn(&x[u], &x[v])',
     '#define bgW0F(j) w = tw + (b << sjs[j]); LD(1); CTL(2)',
     '#define bgWF(j) w += D[j]; LD(1); CTL(1)',
     '#define bgW0I(j) w = tw + ((nh - (b << sj[j])) << sh); LD(1); CTL(4)',
     '#define bgWI(j) w -= D[j]; LD(1); CTL(1)',
     '#define bgR1(M, t, st, h) M(t, (t) + (h))',
     '#define bgR2(M, t, st, h) bgR1(M, t, st, h); bgR1(M, (t) + (st), st, h)',
     '#define bgR4(M, t, st, h) bgR2(M, t, st, h); bgR2(M, (t) + 2 * (st), st, h)',
     '#define bgR8(M, t, st, h) bgR4(M, t, st, h); bgR4(M, (t) + 4 * (st), st, h)',
     '#define bgR16(M, t, st, h) bgR8(M, t, st, h); bgR8(M, (t) + 8 * (st), st, h)',
     '#define bgLX(i) x[i] = base[(i) * s]; LD(1)',
     '#define bgSX(i) base[(i) * s] = x[i]; ST(1)',
     '#define bgLX8(i) bgLX(i); bgLX((i) + 1); bgLX((i) + 2); bgLX((i) + 3); bgLX((i) + 4); bgLX((i) + 5); bgLX((i) + 6); bgLX((i) + 7)',
     '#define bgSX8(i) bgSX(i); bgSX((i) + 1); bgSX((i) + 2); bgSX((i) + 3); bgSX((i) + 4); bgSX((i) + 5); bgSX((i) + 6); bgSX((i) + 7)',
     '#define bgPS8(i) bgPS(i); bgPS((i) + 1); bgPS((i) + 2); bgPS((i) + 3); bgPS((i) + 4); bgPS((i) + 5); bgPS((i) + 6); bgPS((i) + 7)',
     '#define bgPM8(i) bgPM(i); bgPM((i) + 1); bgPM((i) + 2); bgPM((i) + 3); bgPM((i) + 4); bgPM((i) + 5); bgPM((i) + 6); bgPM((i) + 7)',
     '#define bgPS(i) fp_sqr(&x[i], &x[i])',
     '#define bgPM(i) fp_mul(&x[i], &x[i], &cb[i]); LD(1)']


def layers(K):
    for j in range(K):
        half = 1 << (K - 1 - j)
        for tp in range(half):
            yield j, tp, [(t, t + half) for t in range(tp, 1 << K, 2 * half)], half


def emit(lines, parts, ind='    '):
    cur = ind
    for p in parts:
        if len(cur) + len(p) > 150:
            lines.append(cur.rstrip())
            cur = ind
        cur += p + ' '
    if cur.strip():
        lines.append(cur.rstrip())


def runs(M, tp, half, c):
    """butterflies of one twiddle: c of them, at t = tp + m * 2 * half; written as macro runs of at most 16"""
    P = []
    done = 0
    while done < c:
        n = min(16, c - done)
        P.append('bgR%d(%s, %d, %d, %d);' % (n, M, tp + done * 2 * half, 2 * half, half))
        done += n
    return P


PP = []


def flush(L):
    global PP
    emit(L, PP)
    PP = []


def kern_f(K, z):
    nm = 'bgkf%s%d' % ('z' if z else 'G', K)
    L = ['static __attribute__((noinline)) void %s(fp *x, const fp *tw, size_t b, const size_t *D, const int *sjs) {' % nm, '    const fp *w;']
    for j, tp, ts, half in layers(K):
        c = len(ts)
        if tp == 0:
            if z:
                PP.extend(runs('bgBN', tp, half, c))
                if half > 1:
                    flush(L)
                    L.append('    w = tw; /* b == 0: the twiddle at tp == 0 is 1; the pointer is the base register */')
                continue
            PP.extend(['bgW0F(%d);' % j] + runs('bgB', tp, half, c))
        else:
            PP.extend(['bgWF(%d);' % j] + runs('bgB', tp, half, c))
    flush(L)
    L.append('}')
    return L


def kern_i(K, z):
    nm = 'bgki%s%d' % ('z' if z else 'G', K)
    L = ['static __attribute__((noinline)) void %s(fp *x, const fp *tw, size_t b, const size_t *D, const int *sj, int sh, size_t nh) {' % nm, '    const fp *w;']
    allL = list(layers(K))
    for j in reversed(range(K)):
        for jj, tp, ts, half in allL:
            if jj != j:
                continue
            c = len(ts)
            if tp == 0:
                if z:
                    PP.extend(runs('bgJN', tp, half, c))
                    if half > 1:
                        flush(L)
                        L.append('    w = tw + (nh << sh); CTL(1); /* b == 0: the twiddle at tp == 0 is 1 */')
                    continue
                PP.extend(['bgW0I(%d);' % j] + runs('bgJ', tp, half, c))
            else:
                PP.extend(['bgWI(%d);' % j] + runs('bgJ', tp, half, c))
    flush(L)
    L.append('}')
    return L


def lsx(K, m):
    """the body of a load / store / pointwise function: straight-line statements"""
    L = []
    if K >= 3:
        emit(L, ['%s8(%d);' % (m, i) for i in range(0, 1 << K, 8)], '    ')
    else:
        emit(L, ['%s(%d);' % (m, i) for i in range(1 << K)], '    ')
    return L


def helpers(K, fusedk):
    L = ['static __attribute__((noinline)) void bgld%d(fp *x, const fp *base, size_t s) {' % K] + lsx(K, 'bgLX') + ['}']
    L += ['static __attribute__((noinline)) void bgst%d(const fp *x, fp *base, size_t s) {' % K] + lsx(K, 'bgSX') + ['}']
    if fusedk:
        L += ['static __attribute__((noinline)) void bgps%d(fp *x) {' % K] + lsx(K, 'bgPS') + ['}']
        L += ['static __attribute__((noinline)) void bgpm%d(fp *x, const fp *cb) {' % K] + lsx(K, 'bgPM') + ['}']
    return L


def passes(K, inv, z):
    """first-pass (z False: block b = 0 of each group with the z kernel, b = 1 .. s-1 with the general kernel) or last-pass (z True: s == 1, one block per group, z kernel) wrapper"""
    G = 1 << K
    nm = 'bg' + ('pi' if inv else 'pf') + ('F' if z else 'G') + str(K)
    kn = 'bg' + ('ki' if inv else 'kf') + ('z' if z else 'G') + str(K)
    zk = 'bg' + ('ki' if inv else 'kf') + 'z' + str(K)
    args = 'const size_t *D, const int *sj, int sh, size_t nh' if inv else 'const size_t *D, const int *sjs'
    kargs = ('x, tw, b, D, sj, sh, nh' if inv else 'x, tw, b, D, sjs')
    zargs = ('x, tw, 0, D, sj, sh, nh' if inv else 'x, tw, 0, D, sjs')
    L = ['static void %s(fp *row, size_t s, size_t ngrp, const fp *tw, %s) {' % (nm, args),
         '    fp *x = RF; size_t Gs = %d * s; CTL(1);' % G,
         '    for (size_t grp = 0; grp < ngrp; grp++) {',
         '        fp *rb = row + grp * Gs; CTL(1);',
         '        { fp *base = rb;',
         '          bgld%d(x, base, s); CTL(2); %s(%s); CTL(4); bgst%d(x, base, s); CTL(2);' % (K, zk, zargs, K),
         '        }']
    if z:
        L.append('        CTL(3);')
    else:
        L += ['        for (size_t b = 1; b < s; b++) {',
              '            fp *base = rb + b; CTL(1);',
              '            bgld%d(x, base, s); CTL(2); %s(%s); CTL(4); bgst%d(x, base, s); CTL(2);' % (K, kn, kargs, K),
              '            CTL(3);',
              '        }',
              '        CTL(2 + 3);']
    L += ['    }', '    CTL(2);', '}']
    return L


def fused(K, mode):
    G = 1 << K
    L = ['static void bgpu%d_%s(fp *row, size_t ngrp, const fp *tw, const size_t *D, const int *sjs, const int *sj, int sh, size_t nh%s) {'
         % (K, mode, ', const fp *C' if mode == 'mul' else ''),
         '    fp *x = RF;',
         '    for (size_t grp = 0; grp < ngrp; grp++) {',
         '        fp *base = row + grp * %d; CTL(1);' % G]
    if mode == 'mul':
        L.append('        const fp *cb = C + grp * %d; CTL(1);' % G)
    L.append('        bgld%d(x, base, 1); CTL(2);' % K)
    L.append('        bgkfz%d(x, tw, 0, D, sjs); CTL(4);' % K)
    L.append('        bgps%d(x); CTL(2);' % K if mode == 'sq' else '        bgpm%d(x, cb); CTL(2);' % K)
    L.append('        bgkiz%d(x, tw, 0, D, sj, sh, nh); CTL(4);' % K)
    L.append('        bgst%d(x, base, 1); CTL(2);' % K)
    L += ['        CTL(3);', '    }', '    CTL(2);', '}']
    return L


kfs = range(KFMIN, KFMAX + 1)
o += kern_f(KG, False) + kern_i(KG, False) + kern_f(KG, True) + kern_i(KG, True)
for k in kfs:
    o += kern_f(k, True) + kern_i(k, True)
o += helpers(KG, False)
for k in kfs:
    o += helpers(k, True)
o += passes(KG, False, False) + passes(KG, True, False)
for k in kfs:
    o += passes(k, False, True) + passes(k, True, True)
    o += fused(k, 'sq') + fused(k, 'mul')
o.append('static void bg_pf(fp *row, int k, size_t s, size_t ngrp, const fp *tw, const size_t *D, const int *sjs) {')
o.append('    switch (k) { case %d: bgpfG%d(row, s, ngrp, tw, D, sjs); break;' % (KG, KG))
for k in kfs:
    o.append('        case %d: bgpfF%d(row, s, ngrp, tw, D, sjs); break;' % (k, k))
o.append('        default: break; }')
o.append('}')
o.append('static void bg_pi(fp *row, int k, size_t s, size_t ngrp, const fp *tw, const size_t *D, const int *sj, int sh, size_t nh) {')
o.append('    switch (k) { case %d: bgpiG%d(row, s, ngrp, tw, D, sj, sh, nh); break;' % (KG, KG))
for k in kfs:
    o.append('        case %d: bgpiF%d(row, s, ngrp, tw, D, sj, sh, nh); break;' % (k, k))
o.append('        default: break; }')
o.append('}')
o.append('static void bg_pu(fp *row, int k, int mode, size_t ngrp, const fp *tw, const size_t *D, const int *sjs, const int *sj, int sh, size_t nh, const fp *C) {')
o.append('    switch (k) {')
for k in kfs:
    o.append('        case %d: if (mode == 1) bgpu%d_sq(row, ngrp, tw, D, sjs, sj, sh, nh); else bgpu%d_mul(row, ngrp, tw, D, sjs, sj, sh, nh, C); break;' % (k, k, k))
o.append('        default: break; }')
o.append('}')
o.append('#undef bgW0F\n#undef bgWF\n#undef bgW0I\n#undef bgWI\n#undef bgR1\n#undef bgR2\n#undef bgR4\n#undef bgR8\n#undef bgR16\n#undef bgB\n#undef bgBN\n#undef bgJ\n#undef bgJN\n#undef bgLX\n#undef bgSX\n#undef bgPS\n#undef bgPM\n#undef bgLX8\n#undef bgSX8\n#undef bgPS8\n#undef bgPM8')
open('ntt_big.h', 'w', newline='\n').write('\n'.join(o) + '\n')
print('ok', len(o), 'lines')
