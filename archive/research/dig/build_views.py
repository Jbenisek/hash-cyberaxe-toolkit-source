#!/usr/bin/env python3
"""Regenerate OPEN.md, LEVER_CELLS.md, MATRIX.md, CONTRADICTIONS.md from CELLS.jsonl. Pure Python, read-only on the store.
Also runs research/tools/traillab/atlas37_gen.py iff that script reads CELLS.jsonl (else writes a note)."""
import os, sys, subprocess, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import add_cell

HERE = os.path.dirname(os.path.abspath(__file__))
WS = os.path.abspath(os.path.join(HERE, '..', '..'))
GEN = os.path.join(WS, 'research', 'tools', 'traillab', 'atlas37_gen.py')
HASH_ORDER = ['sha256-37', 'sha256-38', 'sha256-39', 'sha256-64', 'sha3-r5', 'sha3-r6', 'sha3-r7', 'blake3-r2', 'blake3-r3', 'blake3-r4', 'poseidon-r1', 'poseidon-r2', 'poseidon-r3', 'poseidon-r4', 'poseidon-r5']
STATUS_ORDER = ['BEDROCK', 'COMPUTED', 'SAMPLED', 'LOCAL_ONLY', 'CLAIMED-UNTESTED', 'KILLED', 'OPEN']
SYM = {'BEDROCK': 'B', 'COMPUTED': 'C', 'SAMPLED': 'S', 'LOCAL_ONLY': 'L', 'CLAIMED-UNTESTED': 'U', 'KILLED': 'K', 'OPEN': 'O'}
PREC = ['KILLED', 'BEDROCK', 'COMPUTED', 'SAMPLED', 'LOCAL_ONLY', 'CLAIMED-UNTESTED', 'OPEN']


def ev(r):
    p, q = r.get('potential_bits'), r.get('prior')
    return p * q if isinstance(p, (int, float)) and isinstance(q, (int, float)) else None


def rowkey(r):
    return (r['row_i'] if r['row_i'] is not None else 9999, r['row_j'] if r['row_j'] is not None else 9999)


def cell(r):
    a, b = r['row_i'], r['row_j']
    return '-' if a is None and b is None else '(%s,%s)' % ('-' if a is None else a, '-' if b is None else b)


def esc(s):
    return str(s).replace('|', '/').replace('\n', ' ')


def write(name, text):
    with open(os.path.join(HERE, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def main():
    allrecs = add_cell.load()
    supmap = add_cell.supersession_map(allrecs)   # old id -> superseding id
    # bookkeeping records (kind=supersession) only carry the link; they are not cells
    recs = [r for r in allrecs if r.get('kind') != 'supersession']
    errs = []
    seen = []
    for r in allrecs:
        e = add_cell.validate(r, seen)
        if e:
            errs.append((r.get('id'), e))
        seen.append(r)
    stamp = ('Generated by build_views.py from CELLS.jsonl (%d cell records, %d superseded by a later record, %d supersession bookkeeping records). Do not edit.'
             % (len(recs), sum(1 for r in recs if r.get('id') in supmap), len(allrecs) - len(recs)))
    sup_ids = set(supmap)
    live = [r for r in recs if r.get('id') not in sup_ids]

    # ---------- OPEN.md
    op = [r for r in live if r['status'] in ('OPEN', 'CLAIMED-UNTESTED')]
    op_sup = [r for r in recs if r['status'] in ('OPEN', 'CLAIMED-UNTESTED') and r.get('id') in sup_ids]
    op.sort(key=lambda r: (-(ev(r) if ev(r) is not None else -1), rowkey(r)))
    L = ['# OPEN and CLAIMED-UNTESTED cells, ranked by expected value', '', stamp, '',
         'EV = potential_bits x prior (the ingestor\'s estimates, not measurements; blank = no estimate, ranked last). '
         'CLAIMED-UNTESTED means an outside model asserted it and we have not tested it (this includes outside "closed" verdicts).', '',
         '| # | hash | cell | object | status | EV (bits) | potential x prior | source | evidence | notes |', '|---|---|---|---|---|---|---|---|---|---|']
    for n, r in enumerate(op, 1):
        e = ev(r)
        L.append('| %d | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (
            n, r['hash'], cell(r), esc(r['object']), r['status'], '' if e is None else '%.3f' % e,
            '' if e is None else '%s x %s' % (r['potential_bits'], r['prior']), esc(r['source']), esc(r['evidence'])[:80], esc(r['notes'])[:160]))
    L += ['', '## By row (all hashes)', '']
    byrow = collections.defaultdict(list)
    for r in op:
        byrow[(r['hash'], r['row_i'])].append(r)
    for hsh in HASH_ORDER:
        keys = sorted([k for k in byrow if k[0] == hsh], key=lambda k: (k[1] is None, k[1] if k[1] is not None else 0))
        if not keys:
            continue
        L.append('### ' + hsh)
        for k in keys:
            L.append('- row %s: %s' % ('(none)' if k[1] is None else k[1], '; '.join('%s %s [%s]' % (cell(r), esc(r['object']), r['status']) for r in sorted(byrow[k], key=rowkey))))
        L.append('')
    L += ['## Superseded (closed by a later record via `supersedes`; hidden from the list above)', '',
          '| id | hash | cell | object | was | closed by |', '|---|---|---|---|---|---|']
    for r in sorted(op_sup, key=lambda r: (r['hash'], rowkey(r), r['id'])):
        L.append('| %s | %s | %s | %s | %s | %s |' % (r['id'], r['hash'], cell(r), esc(r['object']), r['status'], supmap[r['id']]))
    L.append('')
    write('OPEN.md', '\n'.join(L) + '\n')

    # ---------- LEVER_CELLS.md
    lv = [r for r in recs if r['lever']]
    alive = [r for r in lv if r['status'] != 'KILLED' and r.get('id') not in sup_ids]
    sdead = [r for r in lv if r.get('id') in sup_ids]
    dead = [r for r in lv if r['status'] == 'KILLED' and r.get('id') not in sup_ids]
    key = lambda r: (r['hash'] not in HASH_ORDER, HASH_ORDER.index(r['hash']), -(r['gain_bits'] or 0))
    L = ['# Lever cells (every gain, any size)', '', stamp, '',
         'gain_bits: POSITIVE = saving (LEVERS.md writes savings negative). basis: q3 = bits of success probability, T = log2 time, S = memory-rule score, count. Gains are NOT additive unless the notes say so (see MATRIX / CONTRADICTIONS for overlaps).', '']
    for title, grp in (('Alive and untested/measured levers', alive), ('Killed levers (own test)', dead)):
        L += ['## ' + title, '', '| hash | cell | object | status | gain_bits | basis | number | source | own_test | notes |', '|---|---|---|---|---|---|---|---|---|---|']
        for r in sorted(grp, key=key):
            g = r['gain_bits']
            L.append('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (
                r['hash'], cell(r), esc(r['object']), r['status'], '' if g is None else g, r.get('gain_basis', ''),
                esc(r['number'])[:120], esc(r['source']), 'yes' if r['own_test'] else 'no', esc(r['notes'])[:140]))
        L.append('')
    if sdead:
        L += ['## Superseded levers (closed by a later record)', '', '| id | hash | cell | object | was | closed by |', '|---|---|---|---|---|---|']
        for r in sorted(sdead, key=key):
            L.append('| %s | %s | %s | %s | %s | %s |' % (r['id'], r['hash'], cell(r), esc(r['object']), r['status'], supmap[r['id']]))
        L.append('')
    write('LEVER_CELLS.md', '\n'.join(L) + '\n')

    # ---------- CONTRADICTIONS.md
    topics = collections.defaultdict(list)
    for r in recs:
        if r.get('topic'):
            topics[r['topic']].append(r)
    L = ['# Same topic, different numbers', '', stamp, '',
         'A topic is listed when its records carry more than one distinct `number`. Many are not errors (different population, base, or a later refinement); notes say which.', '']
    nconf = 0
    for t in sorted(topics):
        g = topics[t]
        if len({r['number'] for r in g}) > 1:
            nconf += 1
            L += ['## ' + t, '']
            for r in sorted(g, key=lambda r: r['date']):
                L.append(('- (superseded by %s) ' % supmap[r['id']] if r.get('id') in sup_ids else '- ') + '`%s` [%s, %s, own_test=%s] %s -> %s  (%s)' % (r['id'], r['source'], r['status'], r['own_test'], esc(r['object']), esc(r['number']), esc(r['evidence'])[:90]))
            L.append('')
    if not nconf:
        L.append('(none)')
    write('CONTRADICTIONS.md', '\n'.join(L) + '\n')

    # ---------- MATRIX.md
    L = ['# Per-hash matrix summary', '', stamp, '', '## Cells per hash and status', '',
         '| hash | ' + ' | '.join(STATUS_ORDER) + ' | total | levers | own_test | superseded (incl. in counts) |', '|---|' + '---|' * (len(STATUS_ORDER) + 4)]
    tot = collections.Counter()
    for h in HASH_ORDER:
        g = [r for r in recs if r['hash'] == h]
        c = collections.Counter(r['status'] for r in g)
        L.append('| %s | %s | %d | %d | %d | %d |' % (h, ' | '.join(str(c[s]) for s in STATUS_ORDER), len(g), sum(r['lever'] for r in g), sum(r['own_test'] for r in g), sum(1 for r in g if r.get('id') in sup_ids)))
        tot.update(c)
    L.append('| **all** | %s | %d | %d | %d | %d |' % (' | '.join(str(tot[s]) for s in STATUS_ORDER), len(recs), sum(r['lever'] for r in recs), sum(r['own_test'] for r in recs), sum(1 for r in recs if r.get('id') in sup_ids)))
    L += ['', '## Cells per hash and source', '']
    srcs = sorted({r['source'].split(':')[0] for r in recs})
    L += ['| hash | ' + ' | '.join(srcs) + ' |', '|---|' + '---|' * len(srcs)]
    for h in HASH_ORDER:
        L.append('| %s | %s |' % (h, ' | '.join(str(sum(1 for r in recs if r['hash'] == h and r['source'].split(':')[0] == s)) for s in srcs)))
    L += ['', '## sha256-37 grid, hot block (row i = source, column j = reader)', '',
          'Symbol = strongest status among records on that (i,j): K killed, B bedrock, C computed, S sampled, L local-only, U claimed-untested, O open. "+" = a weaker status is also present (e.g. an open question on a cell that also has a result). Blank = no record. Rows with no (i,j) are not shown.', '']
    by = collections.defaultdict(set)
    for r in live:
        if r['hash'] == 'sha256-37' and r['row_i'] is not None and r['row_j'] is not None:
            by[(r['row_i'], r['row_j'])].add(r['status'])
    cols = list(range(14, 27))
    L += ['| i \\ j | ' + ' | '.join(map(str, cols)) + ' |', '|---|' + '---|' * len(cols)]

    def sym(s):
        if not s:
            return ''
        top = [x for x in PREC if x in s][0]
        weaker = len(s) > 1 and any(PREC.index(x) > PREC.index(top) for x in s)
        return SYM[top] + ('+' if weaker else '')
    for i in range(14, 27):
        L.append('| **%d** | %s |' % (i, ' | '.join(sym(by.get((i, j))) for j in cols)))
    outside = sum(1 for k in by if not (14 <= k[0] <= 26 and 14 <= k[1] <= 26))
    L += ['', '%d sha256-37 cells with coordinates sit outside the hot block (rows -4..13 and 27..36); see CELLS.jsonl.' % outside]
    L += ['', '## sha256-37 rows 0..13 and 27..36 with any record', '']
    pr = collections.defaultdict(collections.Counter)
    for r in live:
        if r['hash'] == 'sha256-37' and r['row_i'] is not None and not (14 <= r['row_i'] <= 26):
            pr[r['row_i']][r['status']] += 1
    for i in sorted(pr):
        L.append('- row %d: %s' % (i, ', '.join('%s %d' % (s, n) for s, n in pr[i].items())))
    # atlas generator
    gen_src = open(GEN, encoding='utf-8').read() if os.path.exists(GEN) else ''
    L += ['', '## ATLAS37.md generator', '']
    if 'CELLS.jsonl' in gen_src:
        rc = subprocess.run([sys.executable, GEN], capture_output=True, text=True)
        L.append('atlas37_gen.py reads CELLS.jsonl; ran it (exit %d).' % rc.returncode)
    else:
        L.append('NOTE: atlas37_gen.py does NOT read CELLS.jsonl: its evidence list (E1..E22) and the "?" test table are hard-coded in the script, '
                 'and the D/X/x cells are computed from the step and schedule formulas. It was not run and not edited. To close the loop, change the script to load the '
                 'sha256-37 records of this store for the evidence table and the status of each "?" cell (an OPEN record on (i,j) keeps "?"; a record with a result replaces it).')
    if errs:
        L += ['', '## VALIDATION ERRORS in the store', ''] + ['- %s: %s' % (a, '; '.join(b)) for a, b in errs]
    write('MATRIX.md', '\n'.join(L) + '\n')

    # console summary
    print('records', len(recs), 'validation errors', len(errs))
    for h in HASH_ORDER:
        c = collections.Counter(r['status'] for r in recs if r['hash'] == h)
        print(h, sum(c.values()), dict(c))
    print('status', dict(tot))
    print('contradiction topics', nconf)
    return 1 if errs else 0


if __name__ == '__main__':
    sys.exit(main())
