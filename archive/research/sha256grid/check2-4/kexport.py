# kexport.py - check2-4 (independent check of scout2-4, hole 4).  Reads ONLY the filed r38 module vt38.py (pkgR38a
# base, imported read-only with bytecode writing off) and writes k38.h for chk38.c: round constants, cell
# mask/value/xor-difference of A, E, W for rows 0..37, '+' masks, the two-bit conditions, the published pair's traces
# (rows -4..37, W0..W37, both members), G, the filed first row-17 test constants per G word (c17, mE, vE from
# vt38.tables()), and the 512 embedded variants with their full dense parts (A0..A15, E4..E15, W8..W15 per member).
# usage: python3 -B kexport.py

# Publication path adapter: resolve data paths from the extracted source tree.
def _hca_public_path_text(value):
    if "__HCA_WORKSPACE__/" not in value:
        return value
    import os as _hca_os
    from pathlib import Path as _hca_Path
    root = _hca_os.environ.get("HASHCYBERAXE_WORKSPACE")
    if root is None:
        here = _hca_Path(__file__).resolve().parent
        root = next((str(p) for p in (here, *here.parents) if (p / "research").is_dir()), None)
    if root is None:
        raise FileNotFoundError("Extract the research source tree, or set HASHCYBERAXE_WORKSPACE to its archive directory.")
    return value.replace("__HCA_WORKSPACE__/", str(_hca_Path(root).resolve()).replace("\\", "/") + "/")

import importlib.util, os, sys
sys.dont_write_bytecode = True
P = _hca_public_path_text('__HCA_WORKSPACE__/research/tools/build_pkg/scratch/pkgR38a/base/experiments/vt38.py')
spec = importlib.util.spec_from_file_location("vt38", P); vt = importlib.util.module_from_spec(spec); spec.loader.exec_module(vt)
R, M = vt.R, vt.M
TX, TY = vt.TX, vt.TY
assert vt.compress(vt.PCV, vt.PMX) == vt.compress(vt.PCV, vt.PMY)
L = []
def u32(name, vals):
    L.append("static const uint32_t %s[%d] = {%s};" % (name, len(vals), ",".join("0x%08xu" % (v & M) for v in vals)))
def i32(name, vals):
    L.append("static const int %s[%d] = {%s};" % (name, len(vals), ",".join(str(int(v)) for v in vals)))
L.append("// generated by check2-4/kexport.py from the filed vt38.py; do not edit")
L.append("#include <stdint.h>")
L.append("#define NROW %d" % R)
u32("KC", vt.K[:R])
for k in "AEW":
    u32("CM" + k, [vt.CELL[k][i][0] for i in range(R)])
    u32("CV" + k, [vt.CELL[k][i][1] for i in range(R)])
    u32("CD" + k, [vt.CELL[k][i][2] for i in range(R)])
u32("PLS", vt.PLUS)
TB = vt.TWOBIT; km = {"A": 0, "E": 1, "W": 2}
L.append("#define NTB %d" % len(TB))
i32("TK1", [km[c[0]] for c in TB]); i32("TI1", [c[1] for c in TB]); i32("TB1", [c[2] for c in TB]); i32("TNE", [c[3] for c in TB])
i32("TK2", [km[c[4]] for c in TB]); i32("TI2", [c[5] for c in TB]); i32("TB2", [c[6] for c in TB])
i32("TROW", [max(c[1], c[5]) for c in TB])
for nm, T in (("X", TX), ("Y", TY)):
    u32(nm + "A", [T[0][i] for i in range(-4, R)]); u32(nm + "E", [T[1][i] for i in range(-4, R)]); u32(nm + "W", [T[2][i] for i in range(R)])
u32("GW", vt.G)
vt.tables()
u32("FT_C17", [r[0] for r in vt.GREC]); u32("FT_ME", [r[1] for r in vt.GREC]); u32("FT_VE", [r[2] for r in vt.GREC])
L.append("#define CD7 0x%08xu" % vt.D7); L.append("#define CT7 0x%08xu" % vt.T7); L.append("#define CDW16 0x%08xu" % vt.DW16)
E = vt.emb(); VS = E["VS"]
rows = []
for (j, a1, k) in VS:
    a0, a2 = E["A0"][j], E["A2"][k]
    var, c7 = vt.variant(a0, a1, a2)
    assert vt.valid(var)
    rec = [j, k, a0, a1, a2]
    for (A_, E_, W_) in var:
        rec += [A_[i] for i in range(16)] + [E_[i] for i in range(4, 16)] + [W_[i] for i in range(8, 16)]
    rows.append(rec)
# record layout: j, k, a0, a1, a2, then per member (x, y): A0..A15 (16), E4..E15 (12), W8..W15 (8)  -> 5 + 72 = 77 words
L.append("#define NVS %d" % len(rows))
L.append("#define VREC 77")
L.append("static const uint32_t VSR[%d][77] = {%s};" % (len(rows), ",".join("{" + ",".join("0x%08xu" % (v & M) for v in r) + "}" for r in rows)))
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "k38.h"), "w", newline="\n").write("\n".join(L) + "\n")
# first-test mask as the program builds it versus the SMC's imposed set (E17 x-value cells | PLUS[17])
same = sum(1 for r in vt.GREC if r[1] == (vt.CELL["E"][17][0] | vt.PLUS[17]))
print("exported: variants %d, two-bit conditions %d, G %d; first-test mask == E17 cells | PLUS[17] for %d of 32 G words; "
      "mask bits %s" % (len(rows), len(TB), len(vt.G), same, sorted({bin(r[1]).count("1") for r in vt.GREC})))
