# export38.py - scout2-4 (hole 4, Step-3 relaxation).  Reads ONLY the filed r38 package module
#   research/tools/build_pkg/scratch/pkgR38a/base/experiments/vt38.py  (imported read-only, no side effects)
# and writes consts38.h for smc38r.c: characteristic cells (A, E, W), '+' masks, two-bit conditions keyed at the
# later row, the published semi-free-start pair (rows -4..37 of both members, W0..W37), G (32 words), and the 512
# embedded variants with W8, W9, W10 of both members.  Also prints the published modular differences of rows 16..37.
# usage: python -B export38.py

# Publication path adapter: resolve data paths from the extracted source tree.
def _hca_public_path_text(value):
    if "__HCA_WORKSPACE__/" not in value:
        return value
    import os as _hca_os
    from pathlib import Path as _hca_Path
    root = _hca_os.environ.get("HASHCYBERAXE_WORKSPACE")
    if root is None:
        here = _hca_Path(__file__).resolve().parent
        root = next((str(p) for p in (here, *here.parents) if (p / "research").is_dir()), None)
    if root is None:
        raise FileNotFoundError("Extract the research source tree, or set HASHCYBERAXE_WORKSPACE to its archive directory.")
    return value.replace("__HCA_WORKSPACE__/", str(_hca_Path(root).resolve()).replace("\\", "/") + "/")

import importlib.util, os, sys
P = _hca_public_path_text('__HCA_WORKSPACE__/research/tools/build_pkg/scratch/pkgR38a/base/experiments/vt38.py')
spec = importlib.util.spec_from_file_location("vt38", P); vt = importlib.util.module_from_spec(spec); spec.loader.exec_module(vt)
M = vt.M; R = vt.R
TX, TY = vt.TX, vt.TY
# self-check: the published pair collides and follows every cell of rows 16..37
assert vt.compress(vt.PCV, vt.PMX) == vt.compress(vt.PCV, vt.PMY)
assert all(vt.rowok(TX, TY, i) for i in range(16, R))
E = vt.emb()
out = ["// generated by export38.py from the filed vt38.py (pkgR38a base); do not edit", "#include <stdint.h>",
       "#define NR %d" % R]
def arr(name, vals, t="uint32_t"):
    out.append("static const %s %s[%d] = {%s};" % (t, name, len(vals), ",".join(("0x%08xu" % v) if t == "uint32_t" else str(v) for v in vals)))
arr("KK", vt.K[:R])
for j, nm in enumerate(("M", "V", "D", "P")):
    rows = []
    for k in "AEW":
        rows.append("{" + ",".join("0x%08xu" % vt.CELL[k][i][j] for i in range(R)) + "}")
    out.append("static const uint32_t C%s[3][%d] = {%s};" % (nm, R, ",".join(rows)))
arr("CPL", vt.PLUS)            # '+' pairs: E_i[b] = E_{i-1}[b]
# two-bit conditions (member x), keyed at max row
TB = vt.TWOBIT
kmap = {"A": 0, "E": 1, "W": 2}
out.append("#define NX %d" % len(TB))
arr("XK1", [kmap[c[0]] for c in TB], "int"); arr("XI1", [c[1] for c in TB], "int"); arr("XB1", [c[2] for c in TB], "int")
arr("XNE", [c[3] for c in TB], "int")
arr("XK2", [kmap[c[4]] for c in TB], "int"); arr("XI2", [c[5] for c in TB], "int"); arr("XB2", [c[6] for c in TB], "int")
arr("XROW", [max(c[1], c[5]) for c in TB], "int")
# published pair, rows -4..37 (index i+4), W0..W37
for nm, T in (("PX", TX), ("PY", TY)):
    arr(nm + "A", [T[0][i] for i in range(-4, R)]); arr(nm + "E", [T[1][i] for i in range(-4, R)]); arr(nm + "W", [T[2][i] for i in range(R)])
arr("GW", vt.G)
# variants: (A0 index, A1, A2 index) -> words; W8..W10 of both members
VS = E["VS"]; A0L, A2L = E["A0"], E["A2"]
rec = []
nbad = 0
for (j, a1, k) in VS:
    a0, a2 = A0L[j], A2L[k]
    var, c7 = vt.variant(a0, a1, a2)
    if not vt.valid(var): nbad += 1
    (Ax, Ex, Wx), (Ay, Ey, Wy) = var
    rec.append((a0, a1, a2, Wx[8], Wy[8], Wx[9], Wy[9], Wx[10], Wy[10], c7))
assert nbad == 0
out.append("#define NVAR %d" % len(rec))
out.append("static const uint32_t VAR[%d][10] = {%s};" % (len(rec), ",".join("{" + ",".join("0x%08xu" % v for v in r) + "}" for r in rec)))
# published variant words for reference (W8..W10 of the published S*)
out.append("static const uint32_t PUBW[6] = {0x%08xu,0x%08xu,0x%08xu,0x%08xu,0x%08xu,0x%08xu};" % (TX[2][8], TY[2][8], TX[2][9], TY[2][9], TX[2][10], TY[2][10]))
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "consts38.h"), "w", newline="\n").write("\n".join(out) + "\n")
md = lambda x, y: (x - y) & M
print("variants exported:", len(rec), " two-bit conditions:", len(TB))
print("published modular differences x - y (rows 16..37): i dA dE dW")
for i in range(16, R):
    print("%2d %08x %08x %08x" % (i, md(TX[0][i], TY[0][i]), md(TX[1][i], TY[1][i]), md(TX[2][i], TY[2][i])))
cnt = {}
for i in range(16, R):
    for k in "AEW":
        m, v, d, p = vt.CELL[k][i]
        cnt[i] = cnt.get(i, 0) + bin(m).count("1") + (bin(vt.PLUS[i]).count("1") if k == "E" else 0)
for c in TB: cnt[max(c[1], c[5])] += 1
print("cell + '+' + two-bit condition count per row 16..37:", {i: cnt[i] for i in range(16, R) if cnt[i]}, " total", sum(cnt.values()))
