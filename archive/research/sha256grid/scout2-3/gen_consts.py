"""Emit consts.h for q3gpu.cu from the base package's own reference code (vt38.py) and proof.md A.2.
Read-only use of the base package; no bytecode is written there.  usage: python gen_consts.py > consts.h"""

# Publication path adapter: resolve data paths from the extracted source tree.
def _hca_public_path_text(value):
    if "__HCA_WORKSPACE__/" not in value:
        return value
    import os as _hca_os
    from pathlib import Path as _hca_Path
    root = _hca_os.environ.get("HASHCYBERAXE_WORKSPACE")
    if root is None:
        here = _hca_Path(__file__).resolve().parent
        root = next((str(p) for p in (here, *here.parents) if (p / "research").is_dir()), None)
    if root is None:
        raise FileNotFoundError("Extract the research source tree, or set HASHCYBERAXE_WORKSPACE to its archive directory.")
    return value.replace("__HCA_WORKSPACE__/", str(_hca_Path(root).resolve()).replace("\\", "/") + "/")

import sys, re, importlib.util
sys.dont_write_bytecode = True
BASE = _hca_public_path_text('__HCA_WORKSPACE__/research/tools/build_pkg/scratch/pkgR38a/base')
spec = importlib.util.spec_from_file_location('vt38', BASE + r'\experiments\vt38.py')
vt = importlib.util.module_from_spec(spec); spec.loader.exec_module(vt)

E = vt.emb()
out = []
def arr(name, vals, ty='uint32_t'):
    body = ','.join('0x%08x' % (v & 0xffffffff) for v in vals)
    out.append('HD_CONST %s %s[%d] = {%s};' % (ty, name, len(vals), body))
def iarr(name, vals):
    out.append('HD_CONST int %s[%d] = {%s};' % (name, len(vals), ','.join(str(v) for v in vals)))

out.append('// generated by gen_consts.py from vt38.py (base pkgR38a) -- do not edit')
out.append('#pragma once')
out.append('#include <stdint.h>')
out.append('#ifdef __CUDACC__\n#define HD_CONST static __device__ __constant__ const\n#define HH_CONST static const\n#else\n#define HD_CONST static const\n#define HH_CONST static const\n#endif')
# host + device copies: device in __constant__, host as plain arrays (prefix H_)
arr('KK', vt.K)
for k, nm in enumerate('AEW'):
    arr('CM%s' % nm, [vt.CELL[nm][i][0] for i in range(38)])
    arr('CV%s' % nm, [vt.CELL[nm][i][1] for i in range(38)])
    arr('CD%s' % nm, [vt.CELL[nm][i][2] for i in range(38)])
arr('CP', vt.PLUS)
TX, TY = vt.TX, vt.TY
arr('AXr', [TX[0][i] for i in range(16)]); arr('EXr', [TX[1][i] for i in range(16)]); arr('WXr', [TX[2][i] for i in range(16)])
arr('AYr', [TY[0][i] for i in range(16)]); arr('EYr', [TY[1][i] for i in range(16)]); arr('WYr', [TY[2][i] for i in range(16)])
arr('GW', vt.G)
arr('A0L', E['A0']); arr('A2L', E['A2'])
tb = sorted(vt.TWOBIT, key=lambda c: max(c[1], c[5]))
kind = {'A': 0, 'E': 1, 'W': 2}
iarr('XROW', [max(c[1], c[5]) for c in tb]); iarr('XK1', [kind[c[0]] for c in tb]); iarr('XI1', [c[1] for c in tb])
iarr('XB1', [c[2] for c in tb]); iarr('XNE', [c[3] for c in tb]); iarr('XK2', [kind[c[4]] for c in tb])
iarr('XI2', [c[5] for c in tb]); iarr('XB2', [c[6] for c in tb])
out.append('#define NX %d' % len(tb))
# host copies (identical values) with H_ prefix
def harr(name, vals, ty='uint32_t'):
    out.append('HH_CONST %s H_%s[%d] = {%s};' % (ty, name, len(vals), ','.join(('0x%08x' % (v & 0xffffffff)) if ty == 'uint32_t' else str(v) for v in vals)))
harr('KK', vt.K)
for nm in 'AEW':
    harr('CM%s' % nm, [vt.CELL[nm][i][0] for i in range(38)])
    harr('CV%s' % nm, [vt.CELL[nm][i][1] for i in range(38)])
    harr('CD%s' % nm, [vt.CELL[nm][i][2] for i in range(38)])
harr('CP', vt.PLUS)
harr('AXr', [TX[0][i] for i in range(16)]); harr('EXr', [TX[1][i] for i in range(16)]); harr('WXr', [TX[2][i] for i in range(16)])
harr('AYr', [TY[0][i] for i in range(16)]); harr('EYr', [TY[1][i] for i in range(16)]); harr('WYr', [TY[2][i] for i in range(16)])
harr('GW', vt.G); harr('A0L', E['A0']); harr('A2L', E['A2'])
harr('XROW', [max(c[1], c[5]) for c in tb], 'int'); harr('XK1', [kind[c[0]] for c in tb], 'int'); harr('XI1', [c[1] for c in tb], 'int')
harr('XB1', [c[2] for c in tb], 'int'); harr('XNE', [c[3] for c in tb], 'int'); harr('XK2', [kind[c[4]] for c in tb], 'int')
harr('XI2', [c[5] for c in tb], 'int'); harr('XB2', [c[6] for c in tb], 'int')
# host-only data
harr('VS_J', [v[0] for v in E['VS']], 'int'); harr('VS_A1', [v[1] for v in E['VS']]); harr('VS_K', [v[2] for v in E['VS']], 'int')
out.append('#define NVS %d' % len(E['VS']))
sfs = [w for rec in E['SFS'] for w in rec]
harr('SFS', sfs); out.append('#define NSFS %d' % len(E['SFS']))
# |R_j| from proof.md A.2 (j = 1..256 in A0L order is checked here)
txt = open(BASE + r'\proof.md', encoding='utf-8').read()
a2sec = txt[txt.index('### A.2 The A0 set'):txt.index('### A.3 The A2 list')]
trip = re.findall(r'(\d+) ([0-9a-f]{8}) (\d+)', a2sec)
assert len(trip) == 256, len(trip)
rj = {}
for j, a0, n in trip: rj[int(j)] = (int(a0, 16), int(n))
order = [rj[j + 1] for j in range(256)]
a0l = E['A0']
# map each embedded A0 to its |R_j|
size_of = {a0: n for a0, n in order}
assert set(size_of) == set(a0l), 'A0 sets differ'
out.append('HH_CONST unsigned long long H_RJ[256] = {%s};' % ','.join(str(size_of[a]) for a in a0l))
out.append('#define SR_TOTAL %dULL' % sum(size_of.values()))
out.append('#define D7 0x%08xu' % vt.D7); out.append('#define T7 0x%08xu' % vt.T7); out.append('#define DW16 0x%08xu' % vt.DW16)
out.append('#define F7N 287309824.0')
for i in (8, 9, 10, 11):
    out.append('#define DW%d_D 0x%08xu\n#define DW%d_T 0x%08xu' % (i, vt.DIFF[i][0], i, vt.DIFF[i][1]))
print('\n'.join(x for x in out if x is not None))
# twobit.h: per-row two-bit checks (member x) as templates over an accessor g with A(r), E(r), W(r)
tbl = ['// generated by gen_consts.py -- two-bit conditions of vt38.TWOBIT keyed at row max(i1, i2)', '#pragma once',
       'template<int I> struct TB { template<class G> HD static bool ok(const G&) { return true; } };']
for I in sorted(set(max(c[1], c[5]) for c in vt.TWOBIT)):
    cs = [c for c in vt.TWOBIT if max(c[1], c[5]) == I]
    ex = ' && '.join('((((g.%s(%d) >> %d) ^ (g.%s(%d) >> %d)) & 1u) == %du)' % (c[0], c[1], c[2], c[4], c[5], c[6], c[3]) for c in cs)
    tbl.append('template<> struct TB<%d> { template<class G> HD static bool ok(const G& g) { return %s; } };' % (I, ex))
open('twobit.h', 'w').write('\n'.join(tbl) + '\n')
sys.stderr.write('consts: NX=%d A0=%d A2=%d VS=%d SFS=%d SR=%d\n' % (len(tb), len(a0l), len(E['A2']), len(E['VS']), len(E['SFS']), sum(size_of.values())))
