#!/usr/bin/env python3
"""Make pair_calc_sub.c from the copy of pair_calc_rule.c (research/h8/rule_exact): the same calculator with a
sub-class ("cube") of the class. Research helper of research/pkg7/count, not submitted.

The change is only this: the functions n3r_orig(), n3r_proj() and n3x() already take a pair (xmask, xval) = extra
fixed bits of e1 = Y3 + Y4 (written for pair_calc.c's option -sub); pair_calc_rule.c passes 0, 0. Here the pair comes
from a new option
    -cube MASK VALUE      the whole cube: (e1 AND MASK) == VALUE
which must contain the class mask and agree with the class value (the program stops otherwise); the extra bits are
MASK without the class mask. The printed number of fixed bits (the denominator 2^(96 - fixed bits)) counts them.
Every replacement below must match exactly once, or this script stops.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BS = chr(92)                      # one backslash (kept out of the literals so that no tool can change it)
NL = BS + "n"                     # the two characters of a newline escape in C source
src = open(os.path.join(HERE, "pair_calc_rule.c"), encoding="ascii").read()
EDITS = [
    ("static int g_sc_ok = 0, g_mode = 0, g_usex = 1;",
     "static u32 s_xmask = 0, s_xval = 0;   /* the cube: extra fixed bits of e1 and their values (option -cube) */\n"
     "static int g_sc_ok = 0, g_mode = 0, g_usex = 1;"),
    ("a = n3r_orig(d3, y3, o.tau, o.eps, eta, 0, 0);", "a = n3r_orig(d3, y3, o.tau, o.eps, eta, s_xmask, s_xval);"),
    ("Result r = n3x(d3, y3, o.tau, o.eps, eta, &g_sc, &rs, 0, 0);",
     "Result r = n3x(d3, y3, o.tau, o.eps, eta, &g_sc, &rs, s_xmask, s_xval);"),
    ("b = n3r_proj(d3, y3, o.tau, o.eps, eta, 0, 0);", "b = n3r_proj(d3, y3, o.tau, o.eps, eta, s_xmask, s_xval);"),
    ('        else if (!strcmp(argv[i], "-capx") && i + 1 < argc) N3X_CAP_WORK = exp2(atof(argv[++i]));\n',
     '        else if (!strcmp(argv[i], "-capx") && i + 1 < argc) N3X_CAP_WORK = exp2(atof(argv[++i]));\n'
     '        else if (!strcmp(argv[i], "-cube") && i + 2 < argc) {\n'
     '            u32 cm = (u32)strtoul(argv[i + 1], NULL, 16), cv = (u32)strtoul(argv[i + 2], NULL, 16);\n'
     '            u32 x1c = rol(eta, ROT1), e1m = x1c & LOWBITS, e1v = ~(((d3 + x1c) & WMASK) >> 1) & e1m;\n'
     '            if ((cm & e1m) != e1m || (cv & e1m) != e1v || (cv & ~cm)) {\n'
     '                fprintf(stderr, "cube %08x/%08x is not inside the class %08x/%08x' + NL + '", cm, cv, e1m, e1v); return 2; }\n'
     '            s_xmask = cm & ~e1m; s_xval = cv & s_xmask; i += 2;\n'
     '        }\n'),
    ("    int we = wtl(rol(eta, ROT1));\n", "    int we = wtl(rol(eta, ROT1)) + __builtin_popcount(s_xmask);\n"),
    ('fixed_bits %d rules %d mode %d nocut %d' + NL + '",\n'
     '           d3, d11, delta, y3, y11, eta, we, g_nrule, g_mode, g_nocut);\n',
     'fixed_bits %d rules %d mode %d nocut %d extra_mask %08x extra_value %08x' + NL + '",\n'
     '           d3, d11, delta, y3, y11, eta, we, g_nrule, g_mode, g_nocut, s_xmask, s_xval);\n'),
]
for old, new in EDITS:
    if src.count(old) != 1:
        sys.exit("replacement does not match exactly once: %r (%d)" % (old[:60], src.count(old)))
    src = src.replace(old, new)
src = src.replace("/* Exact class rate of a pin and a class, per outcome",
                  "/* GENERATED by mk_sub.py from pair_calc_rule.c (research/h8/rule_exact): option -cube added. Do not edit.\n"
                  " * Exact class rate of a pin and a class, per outcome", 1)
open(os.path.join(HERE, "pair_calc_sub.c"), "w", encoding="ascii", newline="\n").write(src)
print("pair_calc_sub.c written, %d replacements" % len(EDITS))
