'A6: sample per-frame (outer step) constants of the pkg16f counter batch; write consts.h, frames file, a reference check.'
import hashlib, struct, sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "pkg16f", "pkg", "blake3-r2", "experiments"))
import halfsearch as H

HERE = os.path.dirname(os.path.abspath(__file__))
M = H.MASK

def key_of(o):
    'The six frame words the counter batch (ctr_batch) reads, plus e1 for rule A: Y12, Q=-Y1-w12, w5, C2.b1, C2.c1, e1.'
    return (o["Y12"], (-o["Y1"] - o["w12"]) & M, o["w5"], o["C2.b1"], o["C2.c1"], (H.Y3 + o["Y4"]) & M)

def lane(key, c1):
    'One member of the per-frame table, as ctr_batch computes it: (word, rule A pass).'
    y12, q, w5, cb, cc, e1 = key
    d1 = (c1 - H.Y11) & M
    a1 = H.rol(d1, 16) ^ y12
    y6 = (a1 + q) & M
    y14 = ((H.rol(y6, 7) ^ cb) - cc) & M
    h1 = H.ror(y14 ^ e1, 16)
    b1 = H.ror(c1 ^ y6, 12)
    c2 = (c1 + H.ror(((w5 + a1 + b1) & M) ^ d1, 8)) & M
    c1b = (d1 + H.Y11B) & M
    b1b = H.ror(c1b ^ y6, 12)
    c2b = (c1b + H.ror(((w5 + H.DELTA5 + a1 + b1b) & M) ^ d1, 8)) & M
    eps = c2 ^ c2b
    return H.ETA ^ eps ^ H.rol(H.CTR_BETA ^ eps, 1), int(H.rule_a(h1))

def eight_of(seed, i):
    s = struct.unpack("<8I", hashlib.shake_256(("a6 %s %d" % (seed, i)).encode()).digest(32))
    return list(s)

def main():
    n, mode = int(sys.argv[1]), sys.argv[2]
    if mode == "consts":
        with open(os.path.join(HERE, "consts.h"), "w") as f:
            f.write("// generated by gen_frames.py from halfsearch.py (pkg16f)\n")
            for name, v in (("Y11", H.Y11), ("Y11B", H.Y11B), ("DELTA5", H.DELTA5), ("BETA", H.CTR_BETA),
                            ("ETA", H.ETA), ("CTR_MASK", H.CTR_MASK), ("CTR_VALUE", H.CTR_VALUE)):
                f.write("#define %s 0x%08Xu\n" % (name, v))
            f.write("#define CTR_MEMBERS %du\n" % H.CTR_MEMBERS)
            f.write("#define NRULE %d\n" % len(H.RULE_A))
            f.write("__constant__ unsigned RULE_MASK[NRULE] = {%s};\n" % ", ".join("0x%08Xu" % m for m, _ in H.RULE_A))
            f.write("__constant__ unsigned RULE_VAL[NRULE] = {%s};\n" % ", ".join(str(v) for _, v in H.RULE_A))
        # the reference check: the lane formula against ctr_lane (two full 2-round compressions) on sampled frames
        bad = tot = 0
        for i in range(n):
            o = H.ctr_outer(eight_of("check", i))
            j = (i * 299993) % H.CTR_WORDS
            for c1 in H.ctr_table_word(j)[2]:
                good, ra, word = H.ctr_lane(o, c1)
                if not good:
                    continue
                tot += 1
                bad += (word, ra) != lane(key_of(o), c1)
        print("reference lanes checked", tot, "mismatches", bad)
        return
    # mode "random": all eight words random; mode "w6": only w6 varies (other basis words and member fixed)
    out = bytearray()
    base = eight_of("base", 0)
    for i in range(n):
        if mode == "random":
            e = eight_of("random", i)
        elif mode == "w6":
            e = list(base); e[H.CTR_BASIS.index("w6")] = (base[6] + i) & M
        elif mode == "control":
            e = eight_of("random", i // 3)
        o = H.ctr_outer(e)
        k = list(key_of(o))
        if mode == "control" and i % 3 == 1:   # planted twin 1: top bit of Y12, Q, w5 (DERIVED identical table)
            k[0] ^= 1 << 31; k[1] = (k[1] + (1 << 31)) & M; k[2] = (k[2] + (1 << 31)) & M
        if mode == "control" and i % 3 == 2:   # planted twin 2: top bit of C2.b1, C2.c1 (DERIVED identical table)
            k[3] ^= 1 << 31; k[4] = (k[4] + (1 << 31)) & M
        out += struct.pack("<6I", *k)
    with open(os.path.join(HERE, "frames_%s.bin" % mode), "wb") as f:
        f.write(out)
    print("wrote", n, "frames", mode)

if __name__ == "__main__":
    main()
