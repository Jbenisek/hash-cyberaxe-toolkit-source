#!/usr/bin/env python3
"""gen_consts.py - writes pf_consts.cuh for perframe.cu from the filed program of entry 9a9f3b7b
(research/pkg16/pkg/blake3-r2/experiments/halfsearch.py, sha256 7078cf8a...). Nothing is typed by hand:
  - the constants (IV, X3, X7, X11, X15, W13, K2A..K2D, Y3, Y3', Y11, Y11', delta5, the sub-class pattern, rule A,
    the seven taus of beta*, eps*, beta*, the cube Q*) are read from halfsearch;
  - the device function pf_outer() is a line-by-line translation of halfsearch.ctr_outer (step CO, 77 lines);
  - the filter tables are halfsearch.ctr_tables() (automata (1) on Y9 and (2) on Y3 + Y4 + w8, bit q = CTR_TAUS[q]).
Prints a JSON summary (halfsearch sha256, line count, table sizes)."""
import hashlib
import inspect
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HS_DIR = os.path.join(HERE, "..", "..", "pkg16", "pkg", "blake3-r2", "experiments")
sys.path.insert(0, HS_DIR)
import halfsearch as H  # noqa: E402

OUT_NAMES = ("Y4", "Y12", "Y1", "w12", "C2.a1", "C2.b1", "C2.c1", "C2.d1", "K0.d1", "w5", "Y9", "w8")


def cname(n):
    return n.replace(".", "_")


def translate_outer():
    src = inspect.getsource(H.ctr_outer).splitlines()
    body, names = [], []
    for line in src:
        m = re.match(r'\s+v\["([^"]+)"\] = (.*)$', line)
        if not m:
            continue
        name, expr = m.group(1), m.group(2)
        expr = re.sub(r'v\["([^"]+)"\]', lambda mm: cname(mm.group(1)), expr)
        expr = expr.replace(" & MASK", "")
        expr = re.sub(r"IV\[(\d)\]", r"HS_IV\1", expr)
        for c in ("W13", "X7", "X3", "X11", "X15", "K2A", "K2B", "K2C", "K2D", "CTR_FLAGS"):
            expr = re.sub(r"\b%s\b" % c, "HS_" + c, expr)
        body.append("  const u32 %s = %s;" % (cname(name), expr))
        names.append(name)
    assert len(names) == len(set(names)) and len(names) == 77, len(names)
    return body, names


def table_c(name, t):
    vals = ",".join(str(x) for x in t)
    return "__device__ const unsigned short %s[%d] = {%s};" % (name, len(t), vals)


def main():
    body, names = translate_outer()
    fq, fe = H.ctr_tables()
    assert max(max(t) for t in fq + fe) < 65536
    taus = H.CTR_TAUS
    th = [H.ctr_g(t) for t in taus]
    L = []
    L.append("// generated by gen_consts.py from halfsearch.py (entry 9a9f3b7b); do not edit")
    L.append("typedef unsigned int u32;")
    for i, x in enumerate(H.IV):
        L.append("#define HS_IV%d 0x%08Xu" % (i, x))
    for c in ("W13", "X7", "X3", "X11", "X15", "K2A", "K2B", "K2C", "K2D", "CTR_FLAGS"):
        L.append("#define HS_%s 0x%08Xu" % (c, getattr(H, c)))
    L.append("#define HS_Y3A 0x%08Xu" % H.Y3)
    L.append("#define HS_Y3B 0x%08Xu" % H.Y3B)
    L.append("#define HS_Y11A 0x%08Xu" % H.Y11)
    L.append("#define HS_Y11B 0x%08Xu" % H.Y11B)
    L.append("#define HS_DELTA5 0x%08Xu" % H.DELTA5)
    L.append("#define HS_CLASS_VALUE 0x%08Xu" % H.CLASS_VALUE)
    L.append("#define HS_CLASS_SIZE %du" % H.CLASS_SIZE)
    L.append("__constant__ unsigned char HS_CLASS_FREE[%d] = {%s};" % (len(H.CLASS_FREE),
                                                                      ",".join(map(str, H.CLASS_FREE))))
    L.append("#define HS_NCLASS_FREE %d" % len(H.CLASS_FREE))
    L.append("#define HS_CM 0x%08Xu" % H.CTR_MASK)
    L.append("#define HS_CV 0x%08Xu" % H.CTR_VALUE)
    L.append("#define HS_BETA 0x%08Xu" % H.CTR_BETA)
    L.append("#define HS_EPS 0x%08Xu" % H.CTR_EPS)
    L.append("#define HS_NTAU %d" % len(taus))
    L.append("__constant__ u32 HS_TAU[%d] = {%s};" % (len(taus), ",".join("0x%08Xu" % t for t in taus)))
    L.append("__constant__ u32 HS_TH[%d] = {%s};" % (len(th), ",".join("0x%08Xu" % t for t in th)))
    L.append("#define HS_NRULE %d" % len(H.RULE_A))
    L.append("__constant__ u32 HS_RULE_M[%d] = {%s};" % (len(H.RULE_A), ",".join("0x%08Xu" % m for m, _ in H.RULE_A)))
    L.append("__constant__ u32 HS_RULE_V[%d] = {%s};" % (len(H.RULE_A), ",".join(str(v) for _, v in H.RULE_A)))
    for i, t in enumerate(fq):
        L.append(table_c("FQ%d" % i, t))
    for i, t in enumerate(fe):
        L.append(table_c("FE%d" % i, t))
    L.append("__device__ __forceinline__ u32 hs_rol(u32 x, int r){ return (x << r) | (x >> (32 - r)); }")
    L.append("__device__ __forceinline__ u32 hs_ror(u32 x, int r){ return (x >> r) | (x << (32 - r)); }")
    L.append("#define rol hs_rol")
    L.append("#define ror hs_ror")
    L.append("struct PfOut { u32 %s; };" % ", ".join(cname(n) for n in OUT_NAMES))
    L.append("// class_member: Y4 of member number k (the bits of k on the free positions of e1), as halfsearch")
    L.append("__device__ __forceinline__ u32 hs_class_member(u32 k){")
    L.append("  u32 e1 = HS_CLASS_VALUE;")
    L.append("  #pragma unroll")
    L.append("  for(int j = 0; j < HS_NCLASS_FREE; j++) e1 |= ((k >> j) & 1u) << HS_CLASS_FREE[j];")
    L.append("  return e1 - HS_Y3A;")
    L.append("}")
    L.append("// step CO = halfsearch.ctr_outer, the basis (C0.d1, D2.a1, D2.b1, S11, S4, X9, w6) and Y4")
    L.append("__device__ __forceinline__ void pf_outer(u32 C0_d1, u32 D2_a1, u32 D2_b1, u32 S11, u32 S4, u32 X9, u32 w6,"
             " u32 Y4, PfOut *o){")
    L += body
    for n in OUT_NAMES:
        L.append("  o->%s = %s;" % (cname(n), cname(n)))
    L.append("}")
    L.append("__device__ __forceinline__ u32 pf_look(const unsigned short *t0, const unsigned short *t1,"
             " const unsigned short *t2, const unsigned short *t3, u32 x){")
    L.append("  u32 s = t0[x & 255u]; s = t1[s + ((x >> 8) & 255u)]; s = t2[s + ((x >> 16) & 255u)];"
             " return t3[s + (x >> 24)];")
    L.append("}")
    L.append("#undef rol")
    L.append("#undef ror")
    txt = "\n".join(L) + "\n"
    open(os.path.join(HERE, "pf_consts.cuh"), "w").write(txt)
    hs = hashlib.sha256(open(os.path.join(HS_DIR, "halfsearch.py"), "rb").read()).hexdigest()
    print(json.dumps({"halfsearch_sha256": hs, "outer_lines": len(names), "fq": [len(t) for t in fq],
                      "fe": [len(t) for t in fe], "taus": ["%08x" % t for t in taus], "th": ["%08x" % t for t in th],
                      "cuh_sha256": hashlib.sha256(txt.encode()).hexdigest()}))


if __name__ == "__main__":
    main()
