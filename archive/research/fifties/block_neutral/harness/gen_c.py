'''Generate derive_gen.h: word indices, constants, and straight-line C for the frame-D derivation (split_e3 design order,
77 relations + the Y9 check) and the frame-O derivation (outer basis + T1, 78 relations), from ev.REL exactly as ev.solve1
evaluates them.  Also prints the counted primitive ops (add/sub/xor/rot = 1 each, constants folded).'''
import sys
sys.dont_write_bytecode = True
from common import *   # noqa
TRIAL = ['E1.c1', 'E1.d1', 'E1.a1', 'Y6', 'Y10', 'Y14', 'Y2', 'w0', 'K0.a1', 'T0', 'w1']
NAMES = list(ev.WORDS) + TRIAL
IDX = {w: i for i, w in enumerate(NAMES)}
def cn(w): return 'W_' + w.replace('.', '_')
def V(w): return 'v[%s]' % cn(w)

def emit(r, u):
    '''C expression for word u solved from relation r (mirrors ev.solve1); returns (expr, ops).'''
    if r[0] == 'add':
        cu = r[1][u]; assert abs(cu) == 1
        terms = []; ops = 0
        for w, c in r[1].items():
            if w == u: continue
            # s = r2 + sum c*v[w]; v[u] = -s if cu == 1 else s
            sign = c if cu == -1 else -c
            assert abs(sign) == 1
            terms.append(('+' if sign == 1 else '-') + V(w))
        const = (-r[2]) & M if cu == 1 else r[2] & M
        ops = len(terms) - 1 + (1 if const else 0)
        e = ' '.join(terms)
        if e.startswith('+'): e = e[1:]
        else: e = '0u ' + e; ops += 0 if const else 1
        return '(uint32_t)(%s%s)' % ('0x%08xu + ' % const if const else '', e), max(ops, 0)
    x = []; ru = None; ops = 0; cnt = 0
    for w, k in r[1]:
        if w == u: ru = k; cnt += 1
        else:
            x.append('ROL(%s,%d)' % (V(w), k) if k else V(w)); ops += 1 if k else 0
    assert cnt == 1
    if r[2]: x.append('0x%08xu' % r[2])
    ops += len(x) - 1 + (1 if ru else 0)
    e = '(' + ' ^ '.join(x) + ')'
    return ('ROR(%s,%d)' % (e, ru) if ru else e), ops

def check_expr(r):
    if r[0] == 'add':
        terms = ['%s%s' % ('+' if c == 1 else '-', V(w)) for w, c in r[1].items()]
        assert all(abs(c) == 1 for c in r[1].values())
        e = ' '.join(terms); e = e[1:] if e.startswith('+') else '0u ' + e
        return '(uint32_t)(%s%s)' % ('0x%08xu + ' % r[2] if r[2] else '', e), len(terms) - 1 + (1 if r[2] else 0)
    x = ['ROL(%s,%d)' % (V(w), k) if k else V(w) for w, k in r[1]] + (['0x%08xu' % r[2]] if r[2] else [])
    return '(' + ' ^ '.join(x) + ')', len(x) - 1 + sum(1 for _, k in r[1] if k)

out = ['/* generated by gen_c.py from split_e3/ev.py relations -- do not edit */', '#pragma once', '#include <stdint.h>',
       '#ifndef HD', '#define HD', '#endif',
       '#define ROL(x,n) ((uint32_t)(((x) << (n)) | ((x) >> ((32 - (n)) & 31))))',
       '#define ROR(x,n) ((uint32_t)(((x) >> (n)) | ((x) << ((32 - (n)) & 31))))',
       '#define NW %d' % len(NAMES)]
out.append('enum { ' + ', '.join('%s = %d' % (cn(w), i) for i, w in enumerate(NAMES)) + ' };')
out.append('static const char *const WNAME[NW] = { ' + ', '.join('"%s"' % w for w in NAMES) + ' };')
C = dict(IV0=B3.IV[0], IV4=B3.IV[4], Y3C=hs.Y3, Y11C=hs.Y11, Y3BC=hs.Y3B, Y11BC=hs.Y11B, W4C=hs.W4, W13C=hs.W13,
         W4BC=hs.W4B, DELTA5C=hs.DELTA5, CLASS_MASK_C=hs.CLASS_MASK, CLASS_VALUE_C=hs.CLASS_VALUE, ETA_C=hs.ETA,
         X3C=hs.X3, X7C=hs.X7, X11C=hs.X11, X15C=hs.X15, LEN_A_C=hs.LEN_A, LEN_B_C=hs.LEN_B, FLAGS_C=hs.CTR_FLAGS)
for k, x in C.items(): out.append('#define %s 0x%08xu' % (k, x))
# frame D
lines = []; opsD = 0
for i, (k, w) in enumerate(zip(range(10), FRAME_D[:10])): lines.append('  %s = in[%d];' % (V(w), i))
for i, w in DESIGN.ord:
    e, o = emit(ev.REL[i], w); opsD += o; lines.append('  %s = %s;' % (V(w), e))
ce, co = check_expr(ev.REL[DESIGN.chk]); opsD += co
out.append('/* frame D: in = Y4,Y9,w8, D2.b1,D3.a1,K0.b1,K3.d1,S14,S15, C0.b1(g); %d relations, %d ops + check */' % (len(DESIGN.ord), opsD - co))
out.append('HD static inline uint32_t derive_D_outer(const uint32_t in[10], uint32_t *v) {')
out += lines
out.append('  return %s;  /* check residual (0 when the loop equation %s holds), %d ops */' % (ce, ev.REL[DESIGN.chk][3], co))
out.append('}')
lines = []; opsO = 0
for i, w in enumerate(O_BASIS): lines.append('  %s = in[%d];' % (V(w), i))
for i, w in O_ORDER:
    e, o = emit(ev.REL[i], w); opsO += o; lines.append('  %s = %s;' % (V(w), e))
out.append('/* frame O: in = C0.d1,D2.a1,D2.b1,S11,S4,X9,w6,Y4,T1; %d relations, %d ops */' % (len(O_ORDER), opsO))
out.append('HD static inline void derive_O_outer(const uint32_t in[9], uint32_t *v) {')
out += lines
out.append('}')
def pruned(order, targets):
    '''ops of the relations needed (transitively) for the target words, in that order.'''
    par = {w: (i, [x for x in ev.wset(ev.REL[i]) if x != w]) for i, w in order}
    need, st = set(), list(targets)
    while st:
        x = st.pop()
        if x in need or x not in par: continue
        need.add(x); st += par[x][1]
    return len(need), sum(emit(ev.REL[i], w)[1] for i, w in order if w in need)
E1SIDE = ['Y1', 'w12', 'Y12', 'w5', 'C2.b1', 'C2.c1', 'T1']
nD, pD = pruned(DESIGN.ord, E1SIDE + ['C1.c1', 'Y13'])
nO, pO = pruned(O_ORDER, E1SIDE + ['Y9', 'w8'])
out.append('#define OPS_DERIVE_D %d' % opsD)
out.append('#define OPS_DERIVE_O %d' % opsO)
out.append('#define OPS_PRUNED_D %d  /* %d relations needed for E1 inputs, T1, C2.b1, C2.c1 and the real Y9 */' % (pD, nD))
out.append('#define OPS_PRUNED_O %d  /* %d relations needed for E1 inputs, T1, C2.b1, C2.c1, Y9, w8 */' % (pO, nO))
print('pruned: frame D %d relations %d ops | frame O %d relations %d ops' % (nD, pD, nO, pO))
open(os.path.join(HERE, 'derive_gen.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
print('NW', len(NAMES), 'frame D relations', len(DESIGN.ord), 'ops incl. check', opsD, '| frame O relations', len(O_ORDER), 'ops', opsO)
