#!/usr/bin/env python3
"""Generate co.h: a CUDA device function computing every line of step CO (impl/outer.py LINES, same order),
mechanically translated so the GPU twin cannot drift from the reference."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "impl"))
import outer

cname = lambda s: s.replace(".", "_")

def cx(e):
    if isinstance(e, int):
        return "0x%08xu" % (e & 0xFFFFFFFF)
    if isinstance(e, str):
        return cname(e)
    k = e[0]
    if k == "sum":
        parts = []
        for t in e[1]:
            if isinstance(t, tuple) and t[0] == "neg":
                parts.append("- (" + cx(t[1]) + ")")
            else:
                parts.append("+ (" + cx(t) + ")")
        s = " ".join(parts)
        return "(0u " + s + ")"
    if k == "xor":
        return "((" + cx(e[1]) + ") ^ (" + cx(e[2]) + "))"
    if k == "ror":
        return "ror32(" + cx(e[1]) + ", %d)" % e[2]
    raise ValueError(k)

lines = ["// generated by gen_co.py from impl/outer.py LINES (step CO); do not edit",
         "struct CO { u32 Y9, w8, X13, D1_d1, C0_b1, omega; };",
         "__device__ __forceinline__ CO co_step(u32 C0_d1, u32 D2_a1, u32 D2_b1, u32 S11, u32 S4, u32 X9, u32 w6, u32 Y4) {"]
for name, e in outer.LINES:
    lines.append("  u32 %s = %s;" % (cname(name), cx(e)))
lines.append("  CO r; r.Y9 = Y9; r.w8 = w8; r.X13 = X13; r.D1_d1 = D1_d1; r.C0_b1 = C0_b1;")
lines.append("  r.omega = 0x%08xu + Y4 + w8; return r;" % outer.Y3)
lines.append("}")
assert tuple(outer.OUTER_WORDS) == ("C0.d1", "D2.a1", "D2.b1", "S11", "S4", "X9", "w6")
with open(os.path.join(HERE, "co.h"), "w") as f:
    f.write("\n".join(lines) + "\n")
print("co.h lines", len(outer.LINES))
