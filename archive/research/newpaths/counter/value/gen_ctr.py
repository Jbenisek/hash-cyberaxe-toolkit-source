#!/usr/bin/env python3
"""gen_ctr.py ORDERFILE OUT.inc   (counter/value; research only)
Emit C code for a solving order of the counter arrangement (pin H8, lengths 55/63, counter word T0 free).
Every line 'V <- deps' of the order (copied from scout_recent, cone4_E1b1_B10.txt) is resolved to one G-call
assignment of verify_ctr.relations() (the same resolver as verify_ctr.solve_order) and written as one C statement.
Lines without '*' go to outer_step(), lines with '*' to inner_step().  Basis words are fields set by the caller.
"""
import sys, re
sys.dont_write_bytecode = True
import verify_ctr as V

path, out = sys.argv[1], sys.argv[2]
txt = open(path).read().splitlines()
basis = re.search(r'basis = ([^|]*)', txt[0]).group(1).split()
lines = []
for ln in txt[1:]:
    if '<-' not in ln or 'cone of' in ln:
        continue
    star = ln.lstrip().startswith('*')
    left, right = ln.replace('*', ' ').split('<-')
    lines.append((left.strip(), right.split(), star))

cname = lambda n: n.replace('.', '_')
ROT = {'R16': 16, 'R12': 12, 'R8': 8, 'R7': 7}
CONST = {'Y11': 'Y11A', 'Y3': 'Y3A', 'X3': 'PX3', 'X7': 'PX7', 'X11': 'PX11', 'X15': 'PX15', 'w4': 'PW4',
         'w13': 'PW13', 'w14': '0u', 'w15': '0u'}


def term(a):
    if isinstance(a, int):
        return f'0x{a & 0xffffffff:08x}u'
    if a in CONST:
        return CONST[a]
    return 's->' + cname(a)


def emit(rel, target):
    name, kind, args = rel
    if kind in ('ADD3', 'ADD2'):
        if target == name:
            return f's->{cname(target)} = ' + ' + '.join(term(a) for a in args) + ';'
        rest = list(args); rest.remove(target)
        return f's->{cname(target)} = {term(name)} - ' + ' - '.join(term(a) for a in rest) + ';'
    r = ROT[kind]
    if target == name:
        return f's->{cname(target)} = ror({term(args[0])} ^ {term(args[1])}, {r});'
    other = args[1] if target == args[0] else args[0]
    return f's->{cname(target)} = rol({term(name)}, {r}) ^ {term(other)};'


fields = set(basis)
outer_c, inner_c = [], []
for Vn, deps, star in lines:
    need = set(deps) | {Vn}
    cand = []
    for rel in V.RELS:
        ws = {w for w in V.words_of(rel) if w not in V.PIN}
        if rel[0] == 'E1.b1': ws = {'E1.b1', 'Y6', 'E1.d1'}
        if rel[0] == 'E3.h1': ws = {'E3.h1', 'Y14', 'Y4'}
        if rel[0] == 'E3.e2': ws = {'E3.e2', 'Y4', 'E3.f1', 'w8'}
        if ws == need and (Vn == rel[0] or Vn in rel[2]):
            cand.append(rel)
    assert len(cand) == 1, (Vn, deps, cand)
    rel = cand[0]
    pre = []
    if rel[0] == 'E1.b1':
        assert Vn == 'E1.b1', 'only the forward E1.b1 line is supported'
        pre.append('s->E1_c1 = Y11A + s->E1_d1;'); fields.add('E1.c1')
    if rel[0] in ('E3.h1', 'E3.e2'):
        assert Vn == rel[0], 'only forward E3 lines are supported'
        pre.append('s->E3_a1 = Y3A + s->Y4;'); fields.add('E3.a1')
    code = pre + [emit(rel, Vn)]
    fields |= {w for w in V.words_of(rel) if isinstance(w, str) and w not in V.PIN}
    (inner_c if star else outer_c).extend(code)

FN = '__host__ __device__ static inline' if out.endswith('.cuh') else 'static inline'
with open(out, 'w') as f:
    f.write(f'/* generated by gen_ctr.py from {path}; basis {" ".join(basis)} */\n')
    f.write('typedef struct {\n')
    for n in sorted(fields):
        f.write(f'    u32 {cname(n)};\n')
    f.write('} St;\n')
    f.write('static const char *BASIS_NAMES[] = {' + ', '.join(f'"{b}"' for b in basis) + '};\n')
    f.write(f'#define NBASIS {len(basis)}\n')
    f.write(f'{FN} u32 *basis_ptr(St *s, int i) {{\n    switch (i) {{\n')
    for i, b in enumerate(basis):
        f.write(f'    case {i}: return &s->{cname(b)};\n')
    f.write('    }\n    return 0;\n}\n')
    f.write(f'{FN} void outer_step(St *s) {{\n' + ''.join('    ' + c + '\n' for c in outer_c) + '}\n')
    f.write(f'{FN} void inner_step(St *s) {{\n' + ''.join('    ' + c + '\n' for c in inner_c) + '}\n')
    f.write('static const char *ALL_NAMES[] = {' + ', '.join(f'"{n}"' for n in sorted(fields)) + '};\n')
    f.write(f'#define NALL {len(fields)}\n')
    f.write(f'{FN} u32 get_field(const St *s, int i) {{\n    switch (i) {{\n')
    for i, n in enumerate(sorted(fields)):
        f.write(f'    case {i}: return s->{cname(n)};\n')
    f.write('    }\n    return 0;\n}\n')
print(f'{out}: basis {basis}; outer lines {len(outer_c)}, inner lines {len(inner_c)}, fields {len(fields)}')
