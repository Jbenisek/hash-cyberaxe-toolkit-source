"""Torus maps of the 4x4 state and what they force on the message (shape_torus, 2026-10-08).

For a state map tau that preserves rows (G roles) and maps the column set and the diagonal set onto themselves,
a tau-symmetric 2-round trajectory needs, in each round, the message slot of a G call equal to the slot of its
image call.  The message words must then be constant on the orbits of the group generated by the round-0 slot
map and the round-1 slot map (pulled back through PERM).  #orbits = words of freedom left in the message.
Also lists which maps exist at all (row-preserving automorphisms of the column/diagonal structure).
"""
import itertools

PERM = [2, 6, 3, 10, 7, 0, 4, 13, 1, 11, 12, 5, 9, 14, 15, 8]
COLS = [(0, 4, 8, 12), (1, 5, 9, 13), (2, 6, 10, 14), (3, 7, 11, 15)]
DIAG = [(0, 5, 10, 15), (1, 6, 11, 12), (2, 7, 8, 13), (3, 4, 9, 14)]


def pos_map(f):
    """f: (row, col) -> (row, col'); returns position permutation."""
    return [4 * r + f(r, c) for r in range(4) for c in range(4)]


def call_map(p):
    """Image of each column / diagonal as a set; returns (colmap, diagmap) or None."""
    cs = {frozenset(c): ("C", j) for j, c in enumerate(COLS)}
    ds = {frozenset(d): ("D", j) for j, d in enumerate(DIAG)}
    allc = {**cs, **ds}
    img = {}
    for kind, sets in (("C", COLS), ("D", DIAG)):
        for j, s in enumerate(sets):
            t = frozenset(p[i] for i in s)
            if t not in allc:
                return None
            img[(kind, j)] = allc[t]
    return img


def slot_perm(img):
    """Message slot permutation induced by a call map that preserves step types (C->C, D->D)."""
    sp = [None] * 16
    for (kind, j), (k2, j2) in img.items():
        if kind != k2:
            return None
        base, base2 = (0, 0) if kind == "C" else (8, 8)
        sp[base + 2 * j] = base2 + 2 * j2
        sp[base + 2 * j + 1] = base2 + 2 * j2 + 1
    return sp


def orbits(gens, n=16):
    parent = list(range(n))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for g in gens:
        for i in range(n):
            a, b = find(i), find(g[i])
            if a != b:
                parent[a] = b
    groups = {}
    for i in range(n):
        groups.setdefault(find(i), []).append(i)
    return sorted(groups.values())


def main():
    out = []
    # enumerate all row-preserving maps (r,c) -> (r, pi_r(c)) with pi_r permutations of Z4: 24^4 = 331776
    autos, swaps = [], []
    perms = list(itertools.permutations(range(4)))
    for pis in itertools.product(perms, repeat=4):
        p = [4 * r + pis[r][c] for r in range(4) for c in range(4)]
        img = call_map(p)
        if img is None:
            continue
        kinds = {(k, k2) for (k, _), (k2, _) in img.items()}
        if kinds <= {("C", "C"), ("D", "D")}:
            autos.append((pis, p, img))
        elif kinds <= {("C", "D"), ("D", "C")}:
            swaps.append((pis, p, img))
    out.append(f"row-preserving maps that keep columns->columns, diagonals->diagonals: {len(autos)}")
    for pis, p, img in autos:
        sp = slot_perm(img)
        # round-1 slot s holds message word PERM[s]; symmetric round 1 needs m[PERM[s]] = m[PERM[sp[s]]]
        g0 = sp
        g1 = [None] * 16
        for s in range(16):
            g1[PERM[s]] = PERM[sp[s]]
        orb = orbits([g0, g1])
        shift = [pis[0][c] for c in range(4)]
        out.append(f"  map with row 0 columns -> {shift}: message orbits {orb} -> {len(orb)} free words")
        # state-level fixed space: positions orbits
        porb = orbits([p])
        out.append(f"      state orbits {len(porb)} -> a symmetric state has {len(porb)} free words")
    out.append(f"row-preserving maps that swap columns <-> diagonals: {len(swaps)}")
    for pis, p, img in swaps:
        out.append(f"  rows {[list(x) for x in pis]}: {sorted((f'{k}{j}', f'{k2}{j2}') for (k, j), (k2, j2) in img.items())}")
        fb = all(p[i + 8] == p[i] + 8 for i in range(8))
        out.append(f"      keeps the feed-forward pairs (i, i+8)? {fb}")
    txt = "\n".join(out)
    print(txt)
    with open("orbits.txt", "w") as fh:
        fh.write(txt + "\n")


if __name__ == "__main__":
    main()
