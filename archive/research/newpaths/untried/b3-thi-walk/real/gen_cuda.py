"""gen_cuda.py - generate CUDA sources for the real 32-bit walk measurement from the SHIPPED program (research only).

co_lines.inc : the 77 lines of step CO of experiments/frontline.py (LINES), with the single walk change
               K1.a1 = ROL(K1.d1,16) XOR thi, as C statements over uint32 (inputs: the seven outer words, Y4, fl, thi)
tables.inc   : the flat byte automata F1 (test (1) on Y9) and F2 (test (2) on omega) of frontline.py, restricted to S
consts.inc   : constants (Y3, Y11, DY11, X15, IV, BETA, EPS, TAUS, Q* and class masks)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import walk_model as W  # noqa: E402

F = W.F


def nm(s):
    return s.replace(".", "_")


def src(e):
    if isinstance(e, int):
        return "0x%08Xu" % e
    if isinstance(e, str):
        return nm(e)
    if e[0] == "sum":
        parts = []
        for t in e[1]:
            if type(t) is tuple and t[0] == "neg":
                parts.append("- " + src(t[1]))
            else:
                parts.append("+ " + src(t))
        s = " ".join(parts)
        if s.startswith("+ "):
            s = s[2:]
        else:
            s = "0u " + s
        return "(%s)" % s
    if e[0] == "xor":
        return "(%s ^ %s)" % (src(e[1]), src(e[2]))
    if e[0] == "ror":
        return "RORW(%s, %d)" % (src(e[1]), e[2])
    raise ValueError(e)


def main():
    out = ["/* generated by gen_cuda.py from frontline.LINES with K1.a1 = ROL(K1.d1,16) ^ thi; do not edit */",
           "#define CO_LINES \\"]
    for n, e in W.LINES_W:
        out.append("    const uint32_t %s = %s; \\" % (nm(n), src(e)))
    out.append("    /* end */")
    open(os.path.join(HERE, "co_lines.inc"), "w").write("\n".join(out) + "\n")
    t = ["/* generated by gen_cuda.py: frontline.F1, frontline.F2 (masks restricted to S = 0x5f) */",
         "#define F1_LEN %d" % len(F.F1), "#define F2_LEN %d" % len(F.F2),
         "static const uint32_t H_F1[F1_LEN] = {" + ",".join(str(x) for x in F.F1) + "};",
         "static const uint32_t H_F2[F2_LEN] = {" + ",".join(str(x) for x in F.F2) + "};"]
    open(os.path.join(HERE, "tables.inc"), "w").write("\n".join(t) + "\n")
    c = ["/* generated by gen_cuda.py from frontline.py constants */",
         "#define C_Y3 0x%08Xu" % F.Y3, "#define C_Y11 0x%08Xu" % F.Y11, "#define C_DY11 0x%08Xu" % F.DY11,
         "#define C_X15 0x%08Xu" % F.X15, "#define C_X4W 0x%08Xu" % F.W4,
         "#define C_BETA 0x%08Xu" % F.BETA, "#define C_EPS 0x%08Xu" % F.EPS, "#define C_DELTA5 0x%08Xu" % F.DELTA5,
         "#define C_QMASK 0x%08Xu" % F.QSTAR_MASK, "#define C_QVAL 0x%08Xu" % F.QSTAR_VALUE,
         "#define C_CLASS_VALUE 0x%08Xu" % F.CLASS_VALUE, "#define C_FREE_MASK 0x%08Xu" % F.FREE_MASK,
         "#define C_IV0 0x%08Xu" % F.IV[0], "#define C_IV1 0x%08Xu" % F.IV[1], "#define C_IV4 0x%08Xu" % F.IV[4],
         "#define C_IV5 0x%08Xu" % F.IV[5], "#define C_FLAGS %du" % F.FLAGS,
         "static const uint32_t H_TAUS[7] = {" + ",".join("0x%08Xu" % x for x in F.TAUS) + "};",
         "#define C_E_COUNT %du" % F.E_COUNT, "#define C_SHARE %dull" % F.SHARE]
    open(os.path.join(HERE, "consts.inc"), "w").write("\n".join(c) + "\n")
    print("lines", len(W.LINES_W), "F1", len(F.F1), "F2", len(F.F2))


if __name__ == "__main__":
    main()
